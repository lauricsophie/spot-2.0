  it("should return the number of DECP records for each date", async () => {
    const results: { date: string; count: number }[] = [];

    for (const date of TEST_DATES) {
      const fetchResult = await fetchDecpDocuments({
        datepublicationdonnees: date,
        rows: 1,
        offset: 0,
      });

      expect(fetchResult.success).toBe(true);
      const count = fetchResult.data?.total_count ?? 0;
      results.push({ date, count });
    }

    console.log("\n=== DECP count per date ===");
    for (const { date, count } of results) {
      console.log(`${date} : ${count} DECP`);
    }
    console.log(`Total : ${results.reduce((sum, r) => sum + r.count, 0)} DECP`);
  }, 120_000);
